"""initial schema

Revision ID: 0001
Revises:
Create Date: 2026-08-07

Creates all twenty-two tables of the ApplicantOS schema, hand-written rather than
autogenerated so that every constraint name, referential action and index is a deliberate
decision rather than whatever a diff happened to emit.

Design notes that matter when reading or extending this file:

**Portable column types, not literal ones.** The ``GUID`` / ``JSONType`` / ``EmbeddingType``
/ ``UTCDateTime`` decorators from :mod:`app.database.types` are imported and used directly,
exactly as the models declare them. Substituting ``sa.String(36)`` for ``GUID`` would create
a text primary key on PostgreSQL where the models expect a native ``uuid``, and the mismatch
would only surface as an autogenerate diff — or a cast error — much later.

**Enums are VARCHAR, not native types.** Every enum column in the models is declared
``sa.Enum(..., native_enum=False)`` with ``create_constraint`` left at its default of
``False``, which compiles to a plain ``VARCHAR(n)`` on every backend. This migration spells
that out as :class:`sqlalchemy.String` with the same width, so SQLite works and so adding an
enum member never requires a PostgreSQL type migration. The widths are the longest current
*value* of each enum — that is what SQLAlchemy computes when no explicit length is given —
and they are named as constants below rather than inlined.

**The applications ⇄ documents cycle.** ``applications.resume_version_id`` and
``applications.cover_letter_id`` point at tables that point back at ``applications``, so no
single ordering of ``CREATE TABLE`` statements can satisfy both. The models declare those two
foreign keys ``use_alter=True``, and this migration resolves the cycle the same way
SQLAlchemy's own ``create_all`` does — differently per backend, because the backends differ:

* On PostgreSQL the two constraints are added by ``ALTER TABLE`` once all three tables exist.
* On SQLite, which has no ``ALTER TABLE ... ADD CONSTRAINT``, they are declared inline in
  ``CREATE TABLE applications``. SQLite resolves foreign key targets lazily, so referencing a
  table that does not exist yet is legal.

Either way the constraints end up present on both backends, and the schema this migration
produces is byte-identical to ``Base.metadata.create_all``.

**Referential actions are load-bearing.** ``applications.posting_id`` is ``RESTRICT``, not
``CASCADE``: deleting an applied-to posting must fail loudly rather than erase the evidence
behind "never apply twice". ``knowledge_facts.source_document_id`` is ``SET NULL``, so a
verified fact outlives the document it was extracted from. Company references are
``SET NULL`` everywhere, so merging employer records never destroys application history.

**pgvector.** The extension is created only on PostgreSQL, and only when the ``pgvector``
Python package is importable — that package's presence is precisely the condition under
which :class:`~app.database.types.EmbeddingType` renders a ``vector(n)`` column rather than
falling back to JSON. Creating it unconditionally would fail on a PostgreSQL server that
does not ship the extension, for a schema that would not have used it.
"""

