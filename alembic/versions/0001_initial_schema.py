def _create_deferred_application_foreign_keys(bind: sa.engine.Connection) -> None:
    """Add the two cyclic foreign keys by ``ALTER``, on backends that support it.

    ``applications.resume_version_id`` and ``applications.cover_letter_id`` point at tables
    whose own ``application_id`` columns point back, so neither table can be created with
    both constraints in place. On PostgreSQL the cycle is closed here, after all three tables
    exist. On SQLite there is nothing to do: :func:`_create_applications` already declared
    both constraints inline, because that dialect resolves foreign key targets lazily and
    offers no ``ALTER`` alternative.

    Args:
        bind: The connection migrations are running on.
    """
    if not bind.dialect.supports_alter:
        return
    op.create_foreign_key(
        "fk_applications_resume_version_id_resume_versions",
        "applications",
        "resume_versions",
        ["resume_version_id"],
        ["id"],
        ondelete="SET NULL",
    )
    op.create_foreign_key(
        "fk_applications_cover_letter_id_cover_letters",
        "applications",
        "cover_letters",
        ["cover_letter_id"],
        ["id"],
        ondelete="SET NULL",
    )


def _drop_deferred_application_foreign_keys(bind: sa.engine.Connection) -> None:
    """Break the ``applications`` ⇄ documents cycle before the drop sweep.

    ``cover_letters`` and ``resume_versions`` are dropped while ``applications`` still
    exists, so the pointers into them have to go first. How depends on the backend:

    * With ``ALTER``, the two constraints are dropped outright.
    * Without it (SQLite), the constraints are inline and cannot be removed — so the
      referencing *values* are cleared instead. SQLite performs an implicit ``DELETE`` when
      dropping a table and raises on any surviving foreign key reference to it; nulling both
      columns removes every such reference. Losing those two pointers is irrelevant: the
      tables holding them are about to be dropped by the caller.

    Args:
        bind: The connection migrations are running on.
    """
    if not bind.dialect.supports_alter:
        op.execute(
            "UPDATE applications SET resume_version_id = NULL, cover_letter_id = NULL"
        )
        return
    op.drop_constraint(
        "fk_applications_cover_letter_id_cover_letters",
        "applications",
        type_="foreignkey",
    )
    op.drop_constraint(
        "fk_applications_resume_version_id_resume_versions",
        "applications",
        type_="foreignkey",
    )
