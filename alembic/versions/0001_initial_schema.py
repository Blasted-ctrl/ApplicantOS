def _deferred_application_fks() -> tuple[sa.ForeignKeyConstraint, ...]:
    """Return the two foreign keys that close the ``applications`` ⇄ documents cycle.

    Built by a function rather than held as module constants because a
    :class:`~sqlalchemy.ForeignKeyConstraint` instance belongs to exactly one table and
    cannot be reused between the inline (SQLite) and ``ALTER`` (PostgreSQL) paths.

    Returns:
        Fresh constraint objects for ``resume_version_id`` and ``cover_letter_id``.
    """
    return (
        sa.ForeignKeyConstraint(
            ["resume_version_id"],
            ["resume_versions.id"],
            name="fk_applications_resume_version_id_resume_versions",
            ondelete="SET NULL",
        ),
        sa.ForeignKeyConstraint(
            ["cover_letter_id"],
            ["cover_letters.id"],
            name="fk_applications_cover_letter_id_cover_letters",
            ondelete="SET NULL",
        ),
    )


