def _id_column() -> sa.Column:
    """Return the UUID primary key column shared by every table.

    Values are generated in Python (``uuid.uuid4``) rather than by the database, so an
    object has a stable identity before it is flushed — which is what lets the pipeline
    build a whole object graph and write it in one transaction.
    """
    return sa.Column("id", GUID(), nullable=False)


def _user_id_column(*, nullable: bool = False) -> sa.Column:
    """Return the owning-user foreign key column.

    Args:
        nullable: ``True`` only for ``uploaded_files``, where system-owned artifacts have no
            owning user.
    """
    return sa.Column("user_id", GUID(), nullable=nullable)


def _timestamp_columns() -> tuple[sa.Column, sa.Column]:
    """Return the ``created_at`` / ``updated_at`` audit columns.

    Both carry a server default as well as a Python-side one: the Python default keeps the
    value on the in-memory object immediately, the server default protects rows written by
    a migration or by raw SQL. ``updated_at`` has no ``server_onupdate`` because there is no
    portable spelling of one across PostgreSQL and SQLite; SQLAlchemy's ``onupdate`` hook
    maintains it instead.
    """
    return (
        sa.Column(
            "created_at",
            UTCDateTime(),
            server_default=sa.func.now(),
            nullable=False,
        ),
        sa.Column(
            "updated_at",
            UTCDateTime(),
            server_default=sa.func.now(),
            nullable=False,
        ),
    )


def _deleted_at_column() -> sa.Column:
    """Return the soft-deletion stamp used by ``uploaded_files`` and ``resume_versions``.

    Rows are retired by stamping a timestamp rather than being removed, so history stays
    auditable and foreign keys stay intact (golden rule #6).
    """
    return sa.Column("deleted_at", UTCDateTime(), nullable=True)


def _user_fk(table: str) -> sa.ForeignKeyConstraint:
    """Return the ``user_id -> users.id`` foreign key for *table*.

    ``CASCADE``: deleting a user must not leave orphaned applications, facts, or documents
    behind. On SQLite this is only honoured because :mod:`app.database.session` issues
    ``PRAGMA foreign_keys=ON`` on every connection.

    Args:
        table: The referencing table's name, used to build the constraint name.
    """
    return sa.ForeignKeyConstraint(
        ["user_id"],
        ["users.id"],
        name=f"fk_{table}_user_id_users",
        ondelete="CASCADE",
    )


