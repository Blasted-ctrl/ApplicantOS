def _needs_vector_extension(bind: sa.engine.Connection) -> bool:
    """Return whether ``CREATE EXTENSION vector`` should run for this connection.

    Both conditions must hold, and they are different questions:

    * The dialect must be PostgreSQL — SQLite has no extensions of this kind.
    * The ``pgvector`` **Python package** must be importable, because that is exactly the
      condition under which :class:`~app.database.types.EmbeddingType` renders a
      ``vector(n)`` column. Without it, embedding columns are plain JSON and the server-side
      extension is irrelevant.

    Checking only the dialect would fail the migration on a PostgreSQL server that does not
    ship the extension, for a schema that would not have used it.

    Args:
        bind: The connection migrations are running on.

    Returns:
        ``True`` when the extension is both meaningful and required.
    """
    if bind.dialect.name not in POSTGRES_DIALECT_NAMES:
        return False
    try:
        import pgvector.sqlalchemy  # noqa: F401  - presence check only
    except ImportError:
        return False
    return True


