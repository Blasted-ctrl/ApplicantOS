"""Resume schemas — variants, immutable versions, and the structured document itself.

Golden rule #6 of ``docs/CONTRACTS.md`` §18 shapes this module: a resume is a *generated
view* of the knowledge graph, never a stored file. So:

* :class:`ResumeRead` / :class:`ResumeCreate` describe a **variant** — a name, a template, and
  generation config. A variant holds no resume content at all.
* :class:`ResumeVersionRead` describes one **immutable generation**: the structured document
  that was produced, the :class:`~app.models.knowledge.KnowledgeFact` ids every bullet traces
  back to, the token cost, and the model's reasoning. ``content_json`` is retained forever;
  the rendered PDF is disposable and ``file_id`` goes NULL when cleanup reclaims it.
* :class:`ResumeDocumentSchema` and its parts mirror ``app/documents/models.py``.

**The mirror is deliberately self-contained.** This module does not import
:mod:`app.documents`, because ``app.schemas`` sits below the document renderer in the
dependency graph: the API layer must be importable without pulling in LaTeX, DOCX and HTML
machinery. The shape is defined by ``docs/CONTRACTS.md`` §11 —
``ResumeDocument(contact, summary, sections, skills_line, meta)`` over
``ResumeSection(heading, entries)`` over ``ResumeEntry(title, organization, location,
date_range, bullets, fact_ids)``.

Every field of the document mirror carries a default. A version generated by an older build
must still deserialise, and a read model that raises on historical data would make the audit
trail unreadable exactly when it matters.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any, Final, Literal

from pydantic import Field

from app.schemas.common import Schema

__all__ = [
    "DEFAULT_RENDER_FORMAT",
    "DEFAULT_RESUME_TEMPLATE",
    "RenderFormat",
    "ResumeContactSchema",
    "ResumeCreate",
    "ResumeDocumentSchema",
    "ResumeEntrySchema",
    "ResumePreviewRequest",
    "ResumeRead",
    "ResumeSectionSchema",
    "ResumeVersionRead",
]

#: Output formats the template plugins can render (``docs/CONTRACTS.md`` §11).
RenderFormat = Literal["pdf", "docx", "md", "html"]

#: Format used when a caller does not name one.
DEFAULT_RENDER_FORMAT: Final[str] = "pdf"

#: Template used when neither the variant nor the request names one. Mirrors
#: ``settings.resume_template`` and ``UserPreferences.resume_template``.
DEFAULT_RESUME_TEMPLATE: Final[str] = "modern"

#: Upper bound on bullets a single tailoring pass may select. Beyond this the shrink loop
#: cannot fit one page regardless of font size, so accepting a larger value would only
#: guarantee wasted generation tokens.
MAX_TAILOR_BULLETS: Final[int] = 60

#: Default bullet budget, mirroring ``TailorRequest.max_bullets``.
DEFAULT_TAILOR_BULLETS: Final[int] = 18

# -- page-fit estimation ----------------------------------------------------------------
# ``estimated_lines`` exists so the shrink loop can reject an over-long document *before*
# paying to render it. These constants describe a single-column resume at 10.5pt with
# 0.5in margins, which is the starting point of that loop.

#: Characters that fit on one rendered line at the default font size and margins.
CHARS_PER_LINE: Final[int] = 95

#: Lines consumed by the contact header block (name, contact row, spacing).
HEADER_LINES: Final[int] = 3

#: Lines consumed by a section heading and the rule beneath it.
SECTION_HEADING_LINES: Final[int] = 2

#: Lines consumed by an entry's title/organisation/date row before its bullets.
ENTRY_HEADER_LINES: Final[int] = 1


def _wrapped_lines(text: str) -> int:
    """Return how many rendered lines *text* occupies at :data:`CHARS_PER_LINE`.

    Args:
        text: A summary, bullet, or skills line.

    Returns:
        At least 1 for any non-empty string, 0 for an empty one.
    """
    length = len(text.strip())
    if length == 0:
        return 0
    return -(-length // CHARS_PER_LINE)  # ceiling division without importing math


