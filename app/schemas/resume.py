class ResumeRead(Schema):
    """A named resume variant — configuration, not content.

    ``latest_version`` is not an ORM attribute (the model exposes an ordered ``versions``
    collection, which is lazily loaded); it defaults to ``None`` and is populated by the
    service layer when the caller asked for it.
    """

    id: uuid.UUID
    user_id: uuid.UUID
    name: str
    variant_label: str | None = Field(
        default=None,
        description="Short targeting label passed through as TailorRequest.variant_label.",
    )
    template: str = DEFAULT_RESUME_TEMPLATE
    is_default: bool = Field(
        default=False,
        description="Chosen when a tailoring request names no variant.",
    )
    config: dict[str, Any] = Field(
        default_factory=dict,
        description="Generation overrides: max_bullets, section order, tone.",
    )
    version_count: int = Field(
        default=0,
        description="Number of versions generated; populated by the service layer.",
    )
    latest_version: ResumeVersionRead | None = Field(
        default=None,
        description="Most recent version, when the caller requested it.",
    )
    created_at: datetime
    updated_at: datetime


class ResumeCreate(Schema):
    """Payload for creating a resume variant.

    Only ``name`` is required. Everything else falls back to the user's preferences and the
    packaged defaults, so a user can create a variant without understanding the template
    system first.
    """

    name: str = Field(min_length=1, description="Display name in the resume picker.")
    variant_label: str | None = None
    template: str = Field(
        default=DEFAULT_RESUME_TEMPLATE,
        description="TemplatePlugin used to render versions of this variant.",
    )
    is_default: bool = Field(
        default=False,
        description="Make this the variant chosen when a request names none.",
    )
    config: dict[str, Any] = Field(default_factory=dict)


class ResumeVersionRead(Schema):
    """One immutable generation of a resume, with full provenance.

    ``content_json`` is the permanent record and is always present. ``file_id`` and
    ``download_url`` are frequently ``None``: the rendered artifact is deleted after
    submission when ``settings.delete_temp_resume_after_submit`` is on, and the version can
    always be re-rendered from ``content_json``.
    """

    id: uuid.UUID
    resume_id: uuid.UUID
    application_id: uuid.UUID | None = None
    version_number: int = 1
    content_json: ResumeDocumentSchema = Field(
        default_factory=ResumeDocumentSchema,
        description="The structured resume; canonical and retained forever.",
    )
    render_format: str = DEFAULT_RENDER_FORMAT
    file_id: uuid.UUID | None = Field(
        default=None,
        description="Rendered artifact. None once cleanup has reclaimed the bytes.",
    )
    download_url: str | None = Field(
        default=None,
        description="Link to GET /resumes/versions/{id}/download; set by the API layer.",
    )
    fact_ids: list[str] = Field(
        default_factory=list,
        description="KnowledgeFact ids every bullet traces to.",
    )
    token_usage: dict[str, Any] = Field(default_factory=dict)
    reasoning: str | None = Field(
        default=None,
        description="Model's explanation of which facts it selected and why.",
    )
    bullet_count: int = Field(default=0, description="Number of facts drawn on.")
    has_artifact: bool = Field(
        default=False,
        description="Whether a rendered file is currently attached.",
    )
    deleted_at: datetime | None = None
    created_at: datetime
    updated_at: datetime


class ResumePreviewRequest(Schema):
    """Body of ``POST /resumes/preview`` — tailor a resume without applying to anything.

    This is the "show me what you would send" path. It runs the same
    :class:`app.ai.resume_engine.ResumeEngine` tailoring as a real application, including the
    anti-hallucination checks, but creates no :class:`~app.models.application.Application`
    and submits nothing.

    With ``posting_id`` omitted the engine produces a generic resume from the highest-impact
    facts, which is what the onboarding preview and the "master resume" view render.
    """

    posting_id: uuid.UUID | None = Field(
        default=None,
        description="Posting to tailor against; None produces an untargeted resume.",
    )
    resume_id: uuid.UUID | None = Field(
        default=None,
        description="Variant supplying template and config; None uses the default variant.",
    )
    template: str | None = Field(
        default=None,
        description="Override the variant's template for this preview only.",
    )
    variant_label: str | None = None
    max_bullets: int = Field(
        default=DEFAULT_TAILOR_BULLETS,
        ge=1,
        le=MAX_TAILOR_BULLETS,
        description="Bullet budget for the tailoring pass.",
    )
    render_format: RenderFormat = Field(
        default="pdf",
        description="Format to render the preview in.",
    )
    render: bool = Field(
        default=True,
        description="Render an artifact; False returns the structured document only.",
    )


