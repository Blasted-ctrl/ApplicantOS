class ResumeContactSchema(Schema):
    """The header block of a generated resume.

    Populated from :class:`~app.models.user.User` and
    :class:`~app.models.profile.UserProfile`, never from a model: a fabricated email address
    or phone number would be the most damaging hallucination this system could produce.
    """

    name: str = Field(default="", description="Full name, as printed at the top.")
    email: str | None = None
    phone: str | None = None
    location: str | None = None
    website: str | None = None
    github: str | None = None
    linkedin: str | None = None
    portfolio: str | None = None
    links: dict[str, str] = Field(
        default_factory=dict,
        description="Additional labelled URLs with no named slot.",
    )


class ResumeEntrySchema(Schema):
    """One experience, project, or education entry.

    ``fact_ids`` is the audit trail: every bullet in ``bullets`` corresponds to a
    :class:`~app.models.knowledge.KnowledgeFact` id here. A bullet with no traceable fact is
    a bug (golden rule #7), which is only detectable because the ids travel with the text.
    ``organization``, ``role`` and ``date_range`` are copied verbatim from the source facts —
    never written by the model.
    """

    title: str = Field(default="", description="Role title or project name.")
    organization: str | None = Field(
        default=None,
        description="Employer, school, or project owner. Copied from the source fact.",
    )
    location: str | None = None
    date_range: str | None = Field(
        default=None,
        description='As written by the source ("Jun 2024 - Present"); never re-parsed.',
    )
    bullets: list[str] = Field(default_factory=list)
    fact_ids: list[str] = Field(
        default_factory=list,
        description="KnowledgeFact ids backing `bullets`; the anti-hallucination trail.",
    )


class ResumeSectionSchema(Schema):
    """A titled group of entries — "Experience", "Projects", "Education"."""

    heading: str = Field(default="", description="Section heading as printed.")
    entries: list[ResumeEntrySchema] = Field(default_factory=list)


class ResumeDocumentSchema(Schema):
    """The structured resume — the permanent form stored in ``ResumeVersion.content_json``.

    Mirrors ``app.documents.models.ResumeDocument`` without importing it, so the API layer
    stays independent of the rendering stack. The rendered artifact is disposable; this is
    the canonical record and it is retained forever.
    """

    contact: ResumeContactSchema = Field(default_factory=ResumeContactSchema)
    summary: str | None = Field(
        default=None,
        description="Optional opening paragraph, itself assembled from facts.",
    )
    sections: list[ResumeSectionSchema] = Field(default_factory=list)
    skills_line: str | None = Field(
        default=None,
        description="Flat skills list rendered as a single line for ATS parsers.",
    )
    meta: dict[str, Any] = Field(
        default_factory=dict,
        description="Generation metadata: template, posting id, model, timestamps.",
    )

    def total_bullets(self) -> int:
        """Count every bullet across every entry of every section.

        Returns:
            The total number of bullets in the document.
        """
        return sum(len(entry.bullets) for section in self.sections for entry in section.entries)

    def estimated_lines(self) -> int:
        """Estimate how many rendered lines this document occupies.

        Used by the renderer's page-fit shrink loop to reject an over-long document before
        paying to typeset it. The estimate is intentionally simple and slightly pessimistic:
        a false "too long" costs one extra shrink iteration, while a false "fits" costs a
        wasted render and a two-page resume.

        Returns:
            The estimated line count, including headers and section furniture.
        """
        lines = HEADER_LINES
        if self.summary:
            lines += _wrapped_lines(self.summary)
        for section in self.sections:
            lines += SECTION_HEADING_LINES
            for entry in section.entries:
                lines += ENTRY_HEADER_LINES
                for bullet in entry.bullets:
                    lines += _wrapped_lines(bullet)
        if self.skills_line:
            lines += _wrapped_lines(self.skills_line)
        return lines


